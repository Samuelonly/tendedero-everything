import AppKit
import UniformTypeIdentifiers

/// Hangs what you copy: an image, a piece of text, or a video copied in
/// Finder. Each image is saved as a PNG in Tendedero's own folder, so on the
/// line it behaves like any screenshot. Text is saved as a plain text file
/// there too. A video stays where it is, since a copied video can be large.
///
/// Off until the user turns it on. The pasteboard has no change notification,
/// so its change count is checked twice a second. What was copied is only
/// read once it is one of those three, and never when an app marks the copy
/// as private or temporary.
@MainActor
final class ClipboardWatcher {
    private let onNew: (URL) -> Void
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last thing saved. Some apps put the same content on the clipboard
    /// again; it hangs once, unless it has been taken down since.
    private var last: (data: Data, url: URL)?

    private static let enabledKey = "clipboardEnabled"

    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Copies that are not meant to be kept: password managers and similar
    /// apps mark private or temporary copies, following nspasteboard.org.
    private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Anything bigger is not a screenshot, or a paragraph worth hanging.
    private static let maxImageBytes = 64 * 1024 * 1024
    private static let maxTextBytes = 1 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000

    init(onNew: @escaping (URL) -> Void) {
        self.onNew = onNew
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.privateTypes.isDisjoint(with: $0.types) }) else { return }

        // A file copied in Finder: a video, or an image. It hangs where it
        // lives, so taking it down leaves the file where it was.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let url = urls.first, Self.isHangable(url) {
            hang(url)
            return
        }

        // An image, like a screenshot taken with Control held.
        if let type = pb.availableType(from: [.png, .tiff]),
           let data = pb.data(forType: type), data.count <= Self.maxImageBytes {
            // Decoding a large image takes a moment, so it happens off the main thread.
            DispatchQueue.global(qos: .userInitiated).async { [weak self] in
                let png = ClipboardWatcher.png(from: data, type: type)
                DispatchQueue.main.async {
                    // Copied over again in the meantime: that copy is the one that counts.
                    guard let png, NSPasteboard.general.changeCount == count else { return }
                    self?.save(png, as: "png")
                }
            }
            return
        }

        // Text. A link or an email address on its own is left for whoever
        // wants it: it is not something to hang.
        guard let raw = pb.string(forType: .string) else { return }
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !text.isEmpty, text.utf8.count <= Self.maxTextBytes, !Self.isLink(text) else { return }
        saveText(text)
    }

    /// The line keeps images, videos and text. Anything else copied as a
    /// file is someone else's errand.
    private static func isHangable(_ url: URL) -> Bool {
        if isText(url) { return true }
        guard let type = UTType(filenameExtension: url.pathExtension) else { return false }
        return type.conforms(to: .image) || type.conforms(to: .movie)
    }

    /// A single link or address, with no words around it.
    private static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: \.isWhitespace) else { return false }
        if let url = URL(string: text), let scheme = url.scheme, !scheme.isEmpty { return true }
        if text.lowercased().hasPrefix("www.") { return true }
        // An email address: something@something.something.
        let parts = text.split(separator: "@")
        return parts.count == 2 && parts[1].contains(".")
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func saveText(_ text: String) {
        let data = Data(text.utf8)
        if let last, last.data == data, FileManager.default.fileExists(atPath: last.url.path) { return }
        let url = unique("Text \(Self.stamp())", withExtension: "txt")
        do {
            try FileManager.default.createDirectory(at: OwnFolder.folder, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            last = (data, url)
            onNew(url)
        } catch {
            try? FileManager.default.removeItem(at: url)
            log.error("Could not save copied text: \(error.localizedDescription, privacy: .public)")
        }
    }

    private func save(_ data: Data, as ext: String) {
        if let last, last.data == data, FileManager.default.fileExists(atPath: last.url.path) { return }
        let url = unique("Clipboard \(Self.stamp())", withExtension: ext)
        do {
            try FileManager.default.createDirectory(at: OwnFolder.folder, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            last = (data, url)
            onNew(url)
        } catch {
            try? FileManager.default.removeItem(at: url)
            log.error("Could not save a copied image: \(error.localizedDescription, privacy: .public)")
        }
    }

    /// A new file per copy, so two copies in the same second both hang.
    private func unique(_ name: String, withExtension ext: String) -> URL {
        let fm = FileManager.default
        var url = OwnFolder.folder.appendingPathComponent(name).appendingPathExtension(ext)
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = OwnFolder.folder.appendingPathComponent("\(name) \(n)").appendingPathExtension(ext)
            n += 1
        }
        return url
    }

    private func hang(_ url: URL) {
        if let last, last.url == url, FileManager.default.fileExists(atPath: url.path) { return }
        last = (Data(), url)
        onNew(url)
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
